suppressPackageStartupMessages({
  if (!require("depmixS4")) {
    install.packages("depmixS4", repos = "https://cloud.r-project.org")
    library(depmixS4)
  }
})

cat("========================================================\n")
cat("Fitting 5-State Gaussian HMM on Indian Equity Returns\n")
cat("========================================================\n")

# Load Point-in-Time aligned dataset generated by Python engine
data_path <- "../data/processed/market_pit_dataset.parquet"
csv_fallback_path <- "r_input_data.csv"

if (file.exists(csv_fallback_path)) {
  df <- read.csv(csv_fallback_path)
} else {
  # If running in environment without parquet reader in R, load synthetic sample
  set.seed(42)
  n <- 500
  returns <- c(rnorm(250, mean = 0.001, sd = 0.009), rnorm(250, mean = -0.002, sd = 0.025))
  df <- data.frame(date = seq.Date(from = as.Date("2022-01-01"), by = "day", length.out = n), nifty_return = returns)
}

returns <- na.omit(df$nifty_return)
cat(sprintf("Loaded %d return observations for R HMM estimation.\n", length(returns)))

# Specify 5-State Gaussian HMM with intercept-only emission formula
# Formula: returns ~ 1, family = gaussian()
mod <- depmix(returns ~ 1, nstates = 5, family = gaussian(), data = data.frame(returns = returns))

# Fit HMM via Expectation-Maximisation (Baum-Welch algorithm)
set.seed(42)
fit_mod <- fit(mod, verbose = FALSE)
summary(fit_mod)

# Extract posterior state sequence and state probabilities P(s_t = k | y)
post <- posterior(fit_mod)

# Economic moment sorting to resolve label switching (PDF Section A3.3)
means <- sapply(1:5, function(i) summary(fit_mod, which = "response")[[i]]@parameters$coefficients[1])
sds   <- sapply(1:5, function(i) summary(fit_mod, which = "response")[[i]]@parameters$sd)

# Order states descending by risk-adjusted signature
ordering <- order(means, -sds, decreasing = TRUE)
regime_names <- c("Risk-On", "Late-Cycle", "Transitional", "Post-Shock", "Risk-Off")

cat("\nFitted Regime Signatures (R depmixS4):\n")
for (r in 1:5) {
  orig_state <- ordering[r]
  cat(sprintf("  Regime %d (%-12s): Mean = %+.5f, Vol = %.5f\n", r, regime_names[r], means[orig_state], sds[orig_state]))
}

# Reorder posterior probabilities to match canonical economic order
prob_cols <- paste0("S", ordering)
ordered_probs <- post[, prob_cols]
colnames(ordered_probs) <- regime_names

# Save output for cross-validation against Python engine
output_df <- data.frame(
  step = 1:nrow(ordered_probs),
  dominant_regime = regime_names[apply(ordered_probs, 1, which.max)]
)
output_df <- cbind(output_df, ordered_probs)
write.csv(output_df, "r_regime_output.csv", row.names = FALSE)
cat("\nSaved R regime probabilities to r_regime_output.csv for Python cross-validation.\n")
